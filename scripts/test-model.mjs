import assert from 'node:assert/strict';
import {normalize,recentChats,SECTION_DEFAULTS} from '../source/extension/model.js';
const legacy={mode:'light',accent:'#abc123',sidebarWidth:310,pinned:['character:one',7],showIdentity:true,otherSetting:'keep'};
const migrated=normalize(legacy);
assert.deepEqual(migrated.collapsedSections,{pinned:false,characters:true,history:false,functions:true});
assert.deepEqual(migrated.pinned,['character:one']);
for(const key of ['mode','accent','sidebarWidth','showIdentity','otherSetting'])assert.equal(migrated[key],legacy[key]);
const customized=normalize({...legacy,collapsedSections:{history:true,characters:false,pinned:'invalid'}});
assert.deepEqual(customized.collapsedSections,{pinned:false,characters:false,history:true,functions:true});
customized.collapsedSections.characters=true;
assert.notStrictEqual(customized.collapsedSections,migrated.collapsedSections);
assert.deepEqual(SECTION_DEFAULTS,{pinned:false,characters:true,history:false,functions:true});
const chats=[{file_name:'Z-old.jsonl',lastTime:1},{file_name:'A-new.jsonl',lastTime:30},{file_name:'current.jsonl',lastTime:2},{file_name:'bad-date.jsonl',lastTime:0},{}];
const before=structuredClone(chats);
assert.deepEqual(recentChats(chats,'current').map(x=>x.file_name),['current.jsonl','A-new.jsonl','Z-old.jsonl','bad-date.jsonl']);
assert.deepEqual(recentChats(chats,'missing').map(x=>x.file_name),['A-new.jsonl','current.jsonl','Z-old.jsonl','bad-date.jsonl']);
assert.deepEqual(chats,before);
assert.deepEqual(recentChats([],undefined),[]);
console.log('Settings migration, independent section state and timestamp ordering passed.');
