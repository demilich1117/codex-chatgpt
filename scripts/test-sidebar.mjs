import assert from 'node:assert/strict';
import {normalize} from '../source/extension/model.js';
import {chatKey,chatRef,setFlag,forgetEntry,renameEntry,bookInUse,primaryBook} from '../source/extension/sidebar-state.js';
const target = {avatar:'a.png',data:{extensions:{world:'Book'}}};
const ctx = {characters:[target]};
assert.equal(primaryBook({name:'Book',data:{character_book:{name:'Book'}}}), '');
assert.equal(bookInUse('Book','a.png',{},ctx),false);
assert.equal(bookInUse('Book','a.png',{}, {characters:[target,{...target,avatar:'b.png'}]}),true);
assert.equal(bookInUse('Book','a.png',{world_info:{charLore:[{extraBooks:['Book']}]}},ctx),true);
assert.equal(bookInUse('Book','a.png',{selected_world_info:['Book']},ctx),true);
assert.equal(bookInUse('Book','a.png',{}, {...ctx,chatMetadata:{world_info:'Book'}}),true);
assert.equal(bookInUse('Book','a.png',{}, {...ctx,powerUserSettings:{persona_descriptions:{test:{lorebook:'Book'}}}}),true);
const settings=normalize({pinned:['character:a.png'],collapsedSections:{history:true},futureField:7});
assert.equal(settings.futureField,7);assert.equal(settings.collapsedSections.history,true);
assert.deepEqual(settings.archived,[]);
const first=chatKey('character:a.png','同名.jsonl'),second=chatKey('character:b.png','同名');
assert.notEqual(first,second);assert.deepEqual(chatRef(first),['character:a.png','同名']);
assert.notEqual(chatKey('a:b','c'),chatKey('a','b:c'));
setFlag(settings,'pinned',first,true);setFlag(settings,'pinned',second,true);
setFlag(settings,'archived',first,true);
assert.ok(!settings.pinned.includes(first));assert.ok(settings.pinned.includes(second));
assert.ok(settings.archived.includes(first));
renameEntry(settings,'character:a.png','character:renamed.png');
assert.ok(settings.archived.includes(chatKey('character:renamed.png','同名')));
renameEntry(settings,second,chatKey('character:b.png','新名'));
assert.ok(settings.pinned.includes(chatKey('character:b.png','新名')));
forgetEntry(settings,'character:renamed.png',false);
assert.ok(settings.archived.includes(chatKey('character:renamed.png','同名')),'preserved chats retain their archive state');
forgetEntry(settings,'character:renamed.png',true);
assert.deepEqual(settings.archived,[]);assert.equal(settings.pinned.length,1);
assert.deepEqual(normalize(JSON.parse(JSON.stringify(settings))),settings);
assert.equal(normalize({}).panelWidth,760);
assert.equal(normalize({panelWidth:12}).panelWidth,480);
assert.equal(normalize({panelWidth:2000}).panelWidth,1100);
assert.equal(normalize({panelWidth:'bad'}).panelWidth,760);
assert.equal(normalize({panelWidth:840}).panelWidth,840);
console.log('Sidebar identity, migration, archive, rename and cleanup checks passed.');
